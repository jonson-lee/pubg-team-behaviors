#' Aggregate player rows to one team per match (`matchId + groupId`).
#' Behaviour columns are summed to team totals; teammates share the outcome.
aggregate_teams <- function(dt, behaviour_cols = BEHAVIOUR_COLS) {
  stopifnot(data.table::is.data.table(dt))
  behaviour_cols <- intersect(behaviour_cols, names(dt))

  dt[, c(
    lapply(.SD, function(x) sum(x, na.rm = TRUE)),
    list(
      team_size    = .N,
      winPlacePerc = data.table::first(winPlacePerc),
      matchType    = data.table::first(matchType),
      maxPlace     = data.table::first(maxPlace),
      numGroups    = data.table::first(numGroups)
    )
  ), by = .(matchId, groupId), .SDcols = behaviour_cols][]
}

#' Counts per match mode (players, matches, teams), aligned to STUDY_MODES.
mode_summary <- function(players, teams) {
  modes <- data.table::data.table(
    matchType     = names(EXPECTED_TEAM_SIZE),
    expected_size = unname(EXPECTED_TEAM_SIZE),
    order         = seq_along(EXPECTED_TEAM_SIZE)
  )

  p <- players[, .(players = .N, matches = data.table::uniqueN(matchId)), by = matchType]
  t <- teams[, .(teams = .N), by = matchType]

  out <- merge(modes, p, by = "matchType", all.x = TRUE)
  out <- merge(out, t, by = "matchType", all.x = TRUE)
  for (col in c("players", "matches", "teams")) {
    out[is.na(get(col)), (col) := 0L]
  }
  data.table::setorder(out, order)
  out[, order := NULL][]
}

#' Run integrity checks. Returns a named list of findings.
audit_checks <- function(players, teams) {
  dup_ids <- if ("Id" %in% names(players)) {
    sum(duplicated(players$Id))
  } else {
    NA_integer_
  }

  missing_outcome <- sum(is.na(players$winPlacePerc))
  range_outcome   <- range(players$winPlacePerc, na.rm = TRUE)

  team_size <- teams[, .(n_teams = .N), by = .(matchType, team_size)]
  data.table::setorder(team_size, matchType, team_size)

  inconsistent <- players[
    , .(n_win_values = data.table::uniqueN(winPlacePerc)),
    by = .(matchType, matchId, groupId)
  ][n_win_values > 1L, .N]

  na_by_col <- sort(colSums(is.na(players)), decreasing = TRUE)

  list(
    duplicated_ids         = dup_ids,
    missing_outcome        = missing_outcome,
    outcome_range          = range_outcome,
    team_size_distribution = team_size,
    inconsistent_teams     = inconsistent,
    missing_by_column      = na_by_col
  )
}

#' Render a data.frame/data.table as a Markdown table (character vector of lines).
md_table <- function(x) {
  df <- as.data.frame(x)
  header <- paste0("| ", paste(names(df), collapse = " | "), " |")
  sep    <- paste0("| ", paste(rep("---", ncol(df)), collapse = " | "), " |")
  rows   <- if (nrow(df) == 0L) {
    character(0)
  } else {
    apply(df, 1L, function(r) paste0("| ", paste(r, collapse = " | "), " |"))
  }
  c(header, sep, rows)
}

#' Write the audit findings to a Markdown report.
write_audit_report <- function(findings, players, teams, path) {
  con <- file(path, open = "w", encoding = "UTF-8")
  on.exit(close(con), add = TRUE)

  w <- function(...) writeLines(paste0(...), con)
  w_lines <- function(x) writeLines(x, con)

  ms <- mode_summary(players, teams)

  w("# IBA6101 Data Audit Report")
  w("")
  w("Generated by `code/01_data_audit.R`. Raw files are read-only; derived tables are in ",
    "`data/processed/`.")
  w("")
  w("## Samples")
  w("")
  w("| mode | players | matches | teams | expected team size |")
  w("|---|---:|---:|---:|---:|")
  for (i in seq_len(nrow(ms))) {
    w("| ", ms$matchType[i], " | ", ms$players[i], " | ", ms$matches[i], " | ",
      ms$teams[i], " | ", ms$expected_size[i], " |")
  }
  w("")
  w("## Integrity checks")
  w("")
  w("- Duplicated `Id` rows: ", findings$duplicated_ids)
  w("- Missing `winPlacePerc`: ", findings$missing_outcome)
  w("- `winPlacePerc` range: [", findings$outcome_range[1], ", ",
    findings$outcome_range[2], "]")
  w("- Teams with inconsistent within-team outcome: ", findings$inconsistent_teams)
  w("")
  w("### Team-size distribution")
  w("")
  w_lines(md_table(findings$team_size_distribution))
  w("")
  w("### Missing values by column")
  w("")
  w_lines(md_table(data.frame(
    column  = names(findings$missing_by_column),
    missing = as.integer(findings$missing_by_column),
    row.names = NULL
  )))
  invisible(path)
}
